export const getFeaturedBusinesses = (): Business[] => {
  return businesses.filter((b) => b.featured);
};

export const getLatestBusinesses = (limit: number = 6): Business[] => {
  return [...businesses].reverse().slice(0, limit);
};

export const getBusinessesByCategory = (category: string): Business[] => {
  return businesses.filter((b) => b.category === category);
};

export const getBusinessBySlug = (slug: string): Business | undefined => {
  return businesses.find((b) => b.slug === slug);
};

export const getRelatedBusinesses = (business: Business, limit: number = 3): Business[] => {
  return businesses
    .filter((b) => b.category === business.category && b.id !== business.id)
    .slice(0, limit);
};
